ROOT = Path(__file__).resolve().parents[1]
GENERATED_NOTICE = "<!-- Generated by scripts/generate_knowledge.py. Edit the generator, not this file. -->"


@dataclass(frozen=True)
class KnowledgeDoc:
    path: Path
    title: str
    sections: list[tuple[str, list[str]]]

    def render(self) -> str:
        lines = [GENERATED_NOTICE, "", f"# {self.title}", ""]
        for heading, bullets in self.sections:
            lines.extend([f"## {heading}", ""])
            lines.extend(f"- {bullet}" for bullet in bullets)
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"


def package_scripts(path: Path) -> str:
    data = json.loads(path.read_text(encoding="utf-8"))
    scripts = data.get("scripts", {})
    return ", ".join(f"`npm run {name}`" for name in sorted(scripts))


def backend_tools() -> str:
    data = tomllib.loads((ROOT / "cml-memoryhive-backend/pyproject.toml").read_text(encoding="utf-8"))
    return f"Python `{data['project']['requires-python']}`, Black/Ruff line length `{data['tool']['black']['line-length']}`."


