def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if generated files are stale"
    )
    args = parser.parse_args()

    stale: list[Path] = []
    for doc in docs():
        rendered = doc.render()
        if args.check:
            if (
                not doc.path.exists()
                or doc.path.read_text(encoding="utf-8") != rendered
            ):
                stale.append(doc.path)
        else:
            doc.path.write_text(rendered, encoding="utf-8")

    if stale:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
